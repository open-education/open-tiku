/**
 * 获取面向学生的随机校园风时间段问候语（含周五下午及周末判定）
 * @returns {string} 随机问候语文案
 */
export function getGreeting(): string {
  const now = new Date();
  const day = now.getDay(); // 0 是周日，5 是周五，6 是周六
  const hour = now.getHours();

  let pool: string[];

  // 1. 判定周五下午 (14点及以后)
  if (day === 5 && hour >= 14) {
    pool = GREETING_POOL.FRIDAY_AFTERNOON;
  }
  // 2. 判定周六日全天
  else if (day === 0 || day === 6) {
    pool = GREETING_POOL.WEEKEND;
  }
  // 3. 判定普通工作日时间段
  else {
    if (hour >= 0 && hour < 5) pool = GREETING_POOL.LATE_NIGHT;
    else if (hour >= 5 && hour < 9) pool = GREETING_POOL.EARLY_MORNING;
    else if (hour >= 9 && hour < 11) pool = GREETING_POOL.MORNING;
    else if (hour >= 11 && hour < 13) pool = GREETING_POOL.NOON;
    else if (hour >= 13 && hour < 18) pool = GREETING_POOL.AFTERNOON;
    else pool = GREETING_POOL.EVENING;
  }

  // 从目标文案池中随机抽取一条
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}
